New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

function Get-FontCss($url, $prefix) {
  $css = (Invoke-WebRequest -Uri $url -UserAgent $UA -UseBasicParsing).Content
  # These are variable fonts: every weight shares one file per unicode-range, so
  # the same URL appears many times. Dedupe or we download and commit copies.
  $seen = @{}
  $i = 0
  foreach ($m in [regex]::Matches($css, 'url\((https://[^\)]+)\)')) {
    $remote = $m.Groups[1].Value
    if ($seen.ContainsKey($remote)) { continue }
    $name = "$prefix-$i.woff2"
    $seen[$remote] = $name
    Invoke-WebRequest -Uri $remote -UserAgent $UA -OutFile (Join-Path $OutDir $name) -UseBasicParsing
    $css = $css.Replace($remote, "./$name")
    Write-Host "  $name"
    $i++
  }
  return $css
}

Write-Host "DM Sans:"
$sans = Get-FontCss "https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500;700;900&display=swap" "dm-sans"

Write-Host "Material Symbols (subset, $(($Icons -split ',').Count) icons):"
$symbols = Get-FontCss "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:wght,FILL@100..700,0..1&icon_names=$Icons&display=block" "material-symbols"

$header = "/* Generated by scripts/fetch-fonts.ps1 - do not edit by hand. */`n"
Set-Content -Path (Join-Path $OutDir "fonts.css") -Value ($header + $sans + "`n" + $symbols) -Encoding utf8

Write-Host "`nWrote $OutDir\fonts.css"
