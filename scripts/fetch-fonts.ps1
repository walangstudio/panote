<#
Vendors the app's two webfonts into static/fonts/ so the shipped app never
touches the network. Run once; re-run only when the icon list below changes.

    powershell -ExecutionPolicy Bypass -File scripts/fetch-fonts.ps1

Material Symbols is subsetted to the glyphs the UI actually renders (a few KB
instead of several MB). If you add a new icon to the UI, add it to $Icons and
re-run this, or it will render as its literal name.
#>

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot
$OutDir = Join-Path $Root "static\fonts"
$UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"

$Icons = @(
